export type PhotoCategory = 'monastery' | 'nature' | 'road' | 'group' | 'meal' | 'care' | 'portrait';

export interface TripProgramDay {
  title: string;
  description: string;
}

export interface TripFaqItem {
  question: string;
  answer: string;
}

/** Одна назначенная дата выезда по маршруту. */
export interface TripDeparture {
  /** Демонстрационная будущая дата — требует подтверждения перед публикацией. */
  date: string;
  /** 0 означает, что на эту дату мест нет — сайт вместо бронирования предлагает лист ожидания. */
  seatsLeft: number;
}

export interface Trip {
  slug: string;
  title: string;
  shortDescription: string;
  categories: TripCategory[];
  tags: string[];
  duration: string;
  /** Демонстрационная цена в рублях — требует подтверждения перед публикацией. */
  price: number;
  priceNote: string;
  guide: string;
  pickupPoints: string[];
  /**
   * Назначенные даты выезда, отсортированные по возрастанию. Маршрут проводится и без
   * назначенных дат на ближайшие месяцы — в этом случае массив пустой: карточка и страница
   * поездки всё равно остаются на сайте, но вместо даты и мест показывают, что дата уточняется.
   */
  departures: TripDeparture[];
  photoCategory: PhotoCategory;
  photoAlt: string;
  /** Реальное фото из архива поездок службы (kupina-palomnik.ru). Если не задано — используется заглушка. */
  photo?: string;
  program: TripProgramDay[];
  shrines: string[];
  services: string;
  included: string[];
  extraCosts: string[];
  accommodation: string;
  meals: string;
  transport: string;
  physicalLoad: 'лёгкая' | 'средняя' | 'повышенная';
  physicalLoadNote: string;
  packingList: string[];
  beginnerInfo: string;
  faq: TripFaqItem[];
  cancellationPolicy: string;
}

